package app.vlcinterface.data

import android.app.ActivityManager
import android.content.Context
import android.os.Build
import java.io.File
import java.io.OutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * "Collect all logs": one zip with everything needed to look into a problem, ready to hand over.
 *  - info.txt: app version, phone, Android version, memory, sound engine / screen state, the main settings (no
 *    passwords, no API keys, no addresses' passwords);
 *  - logcat.txt: the app's own system log (Android only lets an app read its own lines), errors first in errors.txt;
 *  - exits.txt: why the app ended the last times (from Android), with the stack traces of crashes, native crashes
 *    and "not responding" when Android kept them;
 *  - logs/: every log page of the app (all errors, network per server, crashes, sound engine, player, …).
 */
object LogPack {
    private val ts = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)

    fun fileName(): String = "vlc-interface-logs_" + SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date()) + ".zip"

    fun write(ctx: Context, out: OutputStream) {
        ZipOutputStream(out).use { z ->
            fun put(name: String, text: String) { z.putNextEntry(ZipEntry(name)); z.write(text.toByteArray()); z.closeEntry() }
            put("info.txt", "generated by vlc interface (Collect all logs) — ${ts.format(Date())}\n\n" + info(ctx))
            val lc = logcat()
            put("logcat.txt", "generated by vlc interface (Collect all logs) — ${ts.format(Date())}\n\n$lc")
            put("errors.txt", "generated by vlc interface (Collect all logs) — ${ts.format(Date())}\n\n" +
                lc.lineSequence().filter { l -> Regex("^\\S+\\s+\\S+\\s+\\d+\\s+\\d+\\s+[EF] ").containsMatchIn(l) || "FATAL" in l || "Exception" in l }.joinToString("\n"))
            put("exits.txt", "generated by vlc interface (Collect all logs) — ${ts.format(Date())}\n\n" + exits(ctx))
            File(ctx.filesDir, "logs").walkTopDown().filter { it.isFile }.forEach { f ->
                try { z.putNextEntry(ZipEntry("logs/" + f.relativeTo(File(ctx.filesDir, "logs")).path)); f.inputStream().use { it.copyTo(z) }; z.closeEntry() } catch (_: Exception) {}
            }
        }
    }

    private fun info(ctx: Context): String = buildString {
        try { ctx.packageManager.getPackageInfo(ctx.packageName, 0).let { appendLine("App: vlc interface ${it.versionName} (${it.longVersionCode})") } } catch (_: Exception) {}
        appendLine("Phone: ${Build.MANUFACTURER} ${Build.MODEL} (${Build.DEVICE})")
        appendLine("Android: ${Build.VERSION.RELEASE} (API ${Build.VERSION.SDK_INT}), ABI ${Build.SUPPORTED_ABIS.joinToString()}")
        try {
            val am = ctx.getSystemService(ActivityManager::class.java)
            val mi = ActivityManager.MemoryInfo().also { am.getMemoryInfo(it) }
            appendLine("Memory: ${mi.availMem / 1048576} MB free of ${mi.totalMem / 1048576} MB, low: ${mi.lowMemory}")
        } catch (_: Exception) {}
        val rt = Runtime.getRuntime()
        appendLine("App memory: ${(rt.totalMemory() - rt.freeMemory()) / 1048576} MB used, max ${rt.maxMemory() / 1048576} MB")
        try { appendLine("Sound engine active: ${app.vlcinterface.player.NativeAudio.active}") } catch (_: Throwable) {}
        try { appendLine("projectM library loaded: ${app.vlcinterface.player.ProjectM.loaded}") } catch (_: Throwable) {}
        try {
            val p = app.vlcinterface.App.instance.player.state.value
            appendLine("Playing: ${p.item?.let { (if (it.isRadio) "radio " else if (it.isMusic) "song " else "video ") + it.title } ?: "nothing"}, playing=${p.isPlaying}")
        } catch (_: Throwable) {}
        try { appendLine("Visualisation: ${app.vlcinterface.alarm.Alarms.current.vis.toJson()}") } catch (_: Throwable) {}
        // Settings without anything secret.
        try {
            val s = app.vlcinterface.App.instance.store.current.settings.toJson { "" }
            listOf("osApiKey", "osUser", "osPass", "password", "pass", "apiKey").forEach { s.remove(it) }
            val keys = s.keys().asSequence().toList()
            keys.filter { Regex("(?i)pass|key|token|secret").containsMatchIn(it) }.forEach { s.remove(it) }
            appendLine("\nSettings:\n" + s.toString(2))
        } catch (_: Throwable) {}
        try {
            val st = app.vlcinterface.App.instance.store.current
            appendLine("\nSources: " + st.sources.joinToString { "${it.name} (${it.proto}, ${it.zone})" })
        } catch (_: Throwable) {}
    }

    /** The app's own system log lines (all buffers it may read), newest at the end. */
    private fun logcat(): String = try {
        val p = ProcessBuilder("logcat", "-d", "-v", "threadtime", "-b", "main,system,crash").redirectErrorStream(true).start()
        val t = p.inputStream.bufferedReader().readText()
        p.waitFor(); t
    } catch (e: Exception) { "Could not read the log: ${e.message}" }

    private fun exits(ctx: Context): String = buildString {
        if (Build.VERSION.SDK_INT < 30) { append("Android 11 or newer needed."); return@buildString }
        try {
            val am = ctx.getSystemService(ActivityManager::class.java)
            am.getHistoricalProcessExitReasons(ctx.packageName, 0, 16).forEach { x ->
                appendLine("== ${ts.format(Date(x.timestamp))}  reason ${x.reason}  status ${x.status}  importance ${x.importance}  pss ${x.pss / 1024} MB")
                appendLine("   ${x.description ?: ""}")
                try {
                    x.traceInputStream?.use { s ->
                        val t = s.readBytes()
                        // Native crash traces are binary (tombstone); text traces (not responding) are kept as they are.
                        if (t.take(64).count { it < 9 } > 4) appendLine("   [native crash trace, ${t.size} bytes]")
                        else appendLine(String(t).lines().take(400).joinToString("\n") { "   $it" })
                    }
                } catch (_: Exception) {}
                appendLine()
            }
        } catch (e: Exception) { append("Could not read: ${e.message}") }
    }
}
